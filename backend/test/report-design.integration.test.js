import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { createApp } from '../dist/src/app.js';
import { config } from '../dist/src/config/env.js';
import { pool } from '../dist/src/database/pool.js';
import { prisma } from '../dist/src/database/prisma.js';
import { getDocument } from 'pdfjs-dist/legacy/build/pdf.mjs';

const target = new URL(config.databaseUrl);
assert.ok(['localhost', '127.0.0.1'].includes(target.hostname) && target.pathname.endsWith('_test'), 'Disposable local _test database only.');
test('report design persists, is admin-only, rejects stale edits and controls real PDF and browser output', async t => {
  await pool.query(await readFile(new URL('../../database/001_schema.sql', import.meta.url), 'utf8'));
  const server = createApp().listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); await prisma.$disconnect(); await pool.end(); });
  const base = `http://127.0.0.1:${server.address().port}/api`;
  async function request(path, token, method = 'GET', body) {
    const response = await fetch(base + path, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: response.status, body: await response.json() };
  }
  const password = 'Synthetic-Report-Design-Only-123';
  const bootstrap = await request('/auth/bootstrap', null, 'POST', { username: 'design_admin', fullName: 'Synthetic Design Admin', password });
  const admin = bootstrap.status === 201 ? bootstrap.body.data : (await request('/auth/login', null, 'POST', { username: 'design_admin', password })).body.data;
  assert.equal((await request('/report-template')).status, 401);
  const initial = (await request('/report-template', admin.token)).body.data;
  assert.equal(initial.template.patientLayout, 'minimal');
  for (const role of ['IT', 'TECHNICIAN', 'AUTHORIZER', 'DOCTOR', 'CATALOGUE_MANAGER']) {
    const username = `design_${role.toLowerCase()}`;
    assert.ok([201, 409].includes((await request('/users', admin.token, 'POST', { username, fullName: username, password, roles: [role] })).status));
    const session = (await request('/auth/login', null, 'POST', { username, password })).body.data;
    assert.equal((await request('/report-template', session.token)).status, 200);
    assert.equal((await request('/report-template', session.token, 'PUT', { template: initial.template, expectedRevision: 0 })).status, 403);
  }
  assert.equal((await request('/report-template', admin.token, 'PUT', { template: { ...initial.template, bandColor: 'url(evil)', footerFontPt: 100 }, expectedRevision: 0 })).status, 400);
  const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE_PATH || 'D:/pharmacy-on/node_modules/playwright-core/index.mjs').href);
  const browser = await chromium.launch({ headless: true }); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1700, height: 1150 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  // The browser runs against the real disposable test API, not fabricated API responses.
  await page.route('**/api/**', async route => {
    const url = new URL(route.request().url());
    await route.fulfill({ response: await route.fetch({ url: base + url.pathname.replace(/^\/api/, '') + url.search }) });
  });
  await page.addInitScript(token => localStorage.setItem('lis_token', token), admin.token);
  const ui = process.env.REPORT_UI_URL || 'http://localhost:4181';
  await page.goto(`${ui}/report-design`);
  await page.getByRole('heading', { name: 'Report design', exact: true }).waitFor();
  await page.getByLabel('Brand name', { exact: true }).fill('CUSTOM LAB');
  await page.getByLabel('Brand font size (pt)', { exact: true }).fill('40');
  await page.getByLabel('Footer services font size (pt)', { exact: true }).fill('9');
  await page.getByLabel('Header text alignment', { exact: true }).selectOption('right');
  await page.getByLabel('Footer text alignment', { exact: true }).selectOption('center');
  await page.getByLabel('Header right-side details alignment', { exact: true }).selectOption('left');
  await page.getByLabel('Footer helpline alignment', { exact: true }).selectOption('center');
  await page.getByLabel('Header space between groups (mm)', { exact: true }).fill('10');
  await page.getByLabel('Footer space between groups (mm)', { exact: true }).fill('8');
  await page.getByLabel('Header text colour', { exact: true }).fill('#eef0ff');
  await page.getByLabel('Footer background colour', { exact: true }).fill('#334455');
  await page.getByRole('button', { name: 'Save design', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Design saved' }).waitFor();
  const saved = (await request('/report-template', admin.token)).body.data;
  assert.equal(saved.revision, 1); assert.equal(saved.template.brandFontPt, 40);
  assert.equal(saved.template.footerFontPt, 9); assert.equal(saved.template.headerAlignment, 'right');
  assert.equal(saved.template.footerBandColor, '#334455');
  assert.equal(saved.template.headerContactAlignment, 'left'); assert.equal(saved.template.footerContactAlignment, 'center');
  assert.equal(saved.template.headerGapMm, 10); assert.equal(saved.template.footerGapMm, 8);
  assert.equal((await request('/report-template', admin.token, 'PUT', { template: initial.template, expectedRevision: 0 })).status, 409);
  const audit = await pool.query("SELECT details FROM system_audit_events WHERE event_type = 'REPORT_TEMPLATE_UPDATED'");
  assert.equal(audit.rows.length, 1); assert.equal(audit.rows[0].details.after.brandName, 'CUSTOM LAB');
  await page.reload();
  await page.getByLabel('Brand name', { exact: true }).waitFor();
  assert.equal(await page.getByLabel('Brand font size (pt)', { exact: true }).inputValue(), '40');
  assert.equal(await page.getByLabel('Header text alignment', { exact: true }).inputValue(), 'right');
  assert.equal(await page.locator('.letterhead-brand').evaluate(el => getComputedStyle(el).textAlign), 'right');
  assert.equal(await page.locator('.letterhead-contact').evaluate(el => getComputedStyle(el).textAlign), 'left');
  assert.equal(await page.getByLabel('Header space between groups (mm)', { exact: true }).inputValue(), '10');
  assert.equal(await page.locator('.letterhead-terms').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(51, 68, 85)');
  const order = (await pool.query("INSERT INTO lab_orders (accession_no, patient_name, uhid, age_value, gender, sample_date, status, sample_status, created_by, authorized_by, authorized_at) VALUES ('DESIGN-TEST-001', 'Synthetic Patient', 'TEST-001', 30, 'Female', NOW(), 'AUTHORIZED', 'APPROVED', $1, $1, NOW()) RETURNING id", [admin.user.id])).rows[0];
  const response = await fetch(`${base}/clinical/orders/${order.id}/report.pdf`, { headers: { Authorization: `Bearer ${admin.token}` } });
  assert.equal(response.status, 200);
  const bytes = new Uint8Array(await response.arrayBuffer());
  const task = getDocument({ data: bytes, useSystemFonts: true });
  const pdf = await task.promise;
  const content = (await (await pdf.getPage(1)).getTextContent()).items;
  assert.ok(content.some(item => item.str === 'CUSTOM LAB'));
  const brandHeight = content.find(item => item.str === 'CUSTOM LAB').height;
  assert.ok(brandHeight > 35 && brandHeight <= 40, 'configured font fits within its bounded header box');
  await task.destroy();
  await page.goto(`${ui}/orders/${order.id}/report`);
  await page.getByRole('button', { name: 'Print report', exact: true }).click();
  const viewer = page.locator('iframe[title="Exact report PDF and print preview"]');
  await viewer.waitFor();
  const printUrl = await viewer.getAttribute('src');
  assert.ok(printUrl.startsWith('blob:'));
  assert.equal(await page.locator('.report-sheet').isVisible(), false);
  const printBytes = await page.evaluate(async url => [...new Uint8Array(await (await fetch(url)).arrayBuffer())], printUrl);
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download PDF', exact: true }).click();
  const downloaded = await downloadEvent;
  const downloadBytes = new Uint8Array(await readFile(await downloaded.path()));
  async function layout(bytes) {
    const document = getDocument({ data: new Uint8Array(bytes), useSystemFonts: true });
    const pdf = await document.promise;
    const pages = [];
    for (let n = 1; n <= pdf.numPages; n++) pages.push((await (await pdf.getPage(n)).getTextContent()).items.map(({ str, transform, width, height }) => ({ str, transform, width, height })));
    await document.destroy(); return pages;
  }
  assert.deepEqual(await layout(printBytes), await layout(downloadBytes), 'Print viewer and downloaded PDF have identical text and geometry');
  const printAudit = await pool.query("SELECT id FROM audit_events WHERE order_id = $1 AND event_type = 'REPORT_PRINT_REQUESTED'", [order.id]);
  assert.equal(printAudit.rows.length, 1);
  await page.goto(`${ui}/report-design`);
  await page.getByRole('button', { name: 'Preview defaults', exact: true }).click();
  await page.getByLabel('Header text alignment', { exact: true }).selectOption('right');
  await page.getByRole('button', { name: 'Align left / right groups', exact: true }).click();
  assert.equal(await page.getByLabel('Header text alignment', { exact: true }).inputValue(), 'left');
  assert.equal(await page.getByLabel('Header right-side details alignment', { exact: true }).inputValue(), 'right');
  await page.getByRole('button', { name: 'Save design', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Design saved' }).waitFor();
  await mkdir(new URL('../test-results/', import.meta.url), { recursive: true });
  await page.screenshot({ path: fileURLToPath(new URL('../test-results/report-design-editor.png', import.meta.url)) });
  await page.locator('.report-sheet').screenshot({ path: fileURLToPath(new URL('../test-results/report-design-preview.png', import.meta.url)) });
  const defaultPdf = await fetch(`${base}/clinical/orders/${order.id}/report.pdf`, { headers: { Authorization: `Bearer ${admin.token}` } });
  await writeFile(new URL('../test-results/report-design-preview.pdf', import.meta.url), Buffer.from(await defaultPdf.arrayBuffer()));
  assert.deepEqual(errors, []);
});
